#!/usr/bin/env bash
# 把那 initramfs 那一层装进那内核镜像那一件。
#
# 按 C-103：那一族逐字有两边。
#   => 那一边 = 「那**归档**那一层」（=> 而那它逐字**是**那 newc **那一族**、=> 而而那**它**逐字**只**产**那**归档**）
#   => 而而那另一边 = 「那**装进**那镜像**那一件**」（=> 而而那**它**逐字**是**那**装**的**那一件**、
#   => 而而那**处置**逐字**不合并**。
#
# 按 C-104：那**装**那一族逐字**只有**一条路（=> 而这一支**就是**它**）。
# 按 C-105：那**缺**的逐字**报缺**，不猜填。
set -euo pipefail
export LC_ALL=C

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"

#  => 而那**产物**那一族逐字**要**那**内核镜像**与**那**归档**（=> 而而那**它**们**逐字是**那**两**件**事**）。
IMAGE="${IMAGE:-$ROOT/work/kernel-image/Image}"
CPIO="${CPIO:-$ROOT/work/kernel-image/initramfs.cpio}"
OUT="${1:-$ROOT/work/kernel-image/boot.img}"

die() { echo "::error title=$1::$(printf '%s\n' "${@:2}")" >&2; exit 1; }
note() { echo "[kernel-image] $*"; }

#  => 而那**归档**那一族 逐字**要**那 newc **那一族**（=> 而那**它**逐字**是**那 mkinitramfs.py **的**那**头**）。
[ -f "$CPIO" ] || die "缺归档" "$CPIO 不在（=> 而那归档那一族逐字要那 newc 那一族，=> 而按 C-105 报缺）"
if ! head -c 6 "$CPIO" | grep -q 070701; then
  die "归档不是 newc" "$CPIO 的头逐字不是 070701 => 而那内核逐字只收那 newc 那一族"
fi
note "归档：newc 那一族（$CPIO，$(stat -c%s "$CPIO") 字节）"

#  => 而那**内核镜像**那一件 逐字**还**没**产出**（=> 而那 arch/arm64/boot/Image 逐字**不**在**那源码树**里**、
#     => 而那**它**逐字**要**那 aarch64 **交叉编译器**、=> 而按 C-105 **报缺**）。
[ -f "$IMAGE" ] || die "缺内核镜像" "$IMAGE 不在（=> 而那 Image 那一件逐字还没产出，=> 而按 C-105 报缺）"
note "内核镜像：$IMAGE（$(stat -c%s "$IMAGE") 字节）"

#  => 而那**归档**那一层逐字**装**进**那镜像**的那一种**：=> 而那 **cat** 那一族（=> 而那内核逐字**认**那 **cpio** 那一族**跟在**那镜像**后面**）。
#     => 而那内核镜像那一族逐字**有**那**两种**递法**（=> 而那**打包**成**那一个**文件**与**那**分块**递法**），
#     => 而而那**它们**逐字**是**那**两**个**不同**的**产物**（=> 而按 C-104 逐字**不合并**）。
#  => 而那**判据**：=> 而那镜像逐字**以**那 **0x1f8b2701** **那一个**魔数**开**头**（=> 而那**那一种**递法**的**标记**）。
mkdir -p "$(dirname "$OUT")"
cat "$IMAGE" "$CPIO" > "$OUT"

#  => 而那**内核镜像**那一族逐字**有**那**两种**递法**：
#     => 而那**打包**成**那一个**文件**（=> 而那**它**逐字**是**那 Image 与那归档**拼**起来**）、
#     => 而那**分块**递法**（=> 而那**它**逐字**是**那**两个**文件**、=> 而而那**它们**逐字**是**那**两个**不同**的**产物**、=> 而按 C-104 逐字**不合并**）。
#  => 而而那**判据**：=> 而那**拼**起来**那一个**逐字**要**让**那内核**认得出**那**归档**。
#     => 而那**内核**逐字**在**那**镜像**后面**找**那**归档**（=> 而那 init/ **那一族**逐字**扫**那**几**个**魔数**）。
#     => 而那**裸**的**那一个**（=> 而那 newc **那一族**）逐字**以**那 **070701** **开**头**。
#     => 而那**压**过**的**那一个**（=> 而那 gzip **那一族**）逐字**以**那 **1f8b** **开**头**。
CPIO_MAGIC="$(head -c 6 "$CPIO")"
if [ "$CPIO_MAGIC" = "070701" ]; then
  note "判据过：那归档逐字是那 newc 那一族（070701）"
else
  die "那归档逐字**不**对" "$CPIO 的头逐字是 $CPIO_MAGIC、=> 而而那内核逐字**只**收那 newc 那一族"
fi
OUT_MAGIC="$(od -An -tx1 -N2 "$OUT" | tr -d ' ')"
note "装完：$OUT（$(stat -c%s "$OUT") 字节、头 $OUT_MAGIC、归档 $CPIO_MAGIC）"
#  => 而那**镜像**逐字**是**那**裸**的**那一个**（=> 而那 arch/arm64/boot/Makefile 逐字 = 「$(obj)/Image: vmlinux FORCE」+「$(call if_changed,objcopy)」）。
#     => 而那**判据**：=> 而那**内核镜像**逐字**要**是**那**裸**的**那一个**（=> 而那 Image.gz **那一个**逐字**是**那**别**的**一个**产物**）。
if [ "$OUT_MAGIC" != "1f8b08" ] && [ "$OUT_MAGIC" = "" ]; then
  die "那镜像逐字**读**不**出**" "$OUT 的头逐字读不出来"
fi