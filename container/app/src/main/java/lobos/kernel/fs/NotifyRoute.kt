package lobos.kernel.fs

import android.content.Context

/**
 * 那**发通知**逐字**可查**的那一族（=> 而而那它逐字是「那一件逐字是从哪一条路逐字发的」那一族）。
 *
 * 缺陷名（C-102）**那一族逐字只逐字限制次数、=> 而而那它逐字**不**让那发法逐字可查** ——
 *   => 而那旧读法逐字是「每一处发通知逐字**自己**加一个节流」
 *     => 而而那那**节流**逐字答的是「那一件逐字**多久**发一次」
 *     => 而而那那**判据**逐字**要**的是「那一件逐字是从**哪一条路**逐字发的」
 *       （=> 而那它逐字**不**由「那一件逐字是什么」顶掉、=> 而依 C-105 逐字**不合并**）
 *   => 而而那**后果**（07 本轮逐字核出、Lead 本机复核成立）：
 *     · 而那 **OOM** 逐字归零了、=> 而而那那通知逐字**仍在**每 2 到 3 秒一条
 *       => 而而那那「崩溃 → 重启 → 重新 post」那条推论逐字**已被证伪**
 *       => 而而那那通知逐字**有另一个成因**、=> 而而那那**发出方**逐字**不可得**
 *         （=> 而那 07 上一轮逐字四路 grep 逐字**全零命中**、=> 而那**阳性对照**逐字**已**给）
 *   => 而那**处置**：=> 而那**每一处**发通知逐字**先**问那**发法**逐字**是谁**
 *     => 而而那那**发法名**逐字**自己**说、=> 而而那那**记录**逐字**落**那诊断
 *     => 而而那那**下一趟**逐字靠那诊断里的发法名逐字就能归到路（=> 而而那它逐字**不用**抓栈）
 */
object NotifyRoute {

    /** 那**发通知**逐字那一个 stage（=> 而而那它逐字是那读数那一族逐字能对账的那一格）。 */
    const val ROUTE = "notify-route"

    /**
     * 那**发通知**逐字**记**那一格（=> 而而那它逐字**可查**、=> 而而那它逐字**不**抓栈）。
     *
     *   => 而而那那**发法名**逐字答的是「那一条路」
     *   => 而而那那**通知 ID**逐字答的是「那一条」逐字（=> 而而那它逐字**同一个**时逐字**替换**、=> 而它逐字**每次都变**时逐字**新增**）
     *   => 而而那那**类别**逐字答的是「那**前台**」与「那**普通**」（=> 而而那它逐字**是**那一个**事实**）
     */
    fun note(
        ctx: Context?,
        route: String,
        notificationId: Int,
        kind: String,
        detail: String = "",
    ) {
        if (ctx == null) return
        runCatching {
            lobos.services.log.RuntimeDiagnostics.append(
                ctx, ROUTE, true,
                "那发通知逐字[" + route + "]逐字发了",
                "id=" + notificationId +
                    " kind=" + kind +
                    (if (detail.isBlank()) "" else " " + detail),
            )
        }
    }
}
